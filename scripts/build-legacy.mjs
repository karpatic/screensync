import {build} from 'esbuild';
import {transformAsync} from '@babel/core';
import {writeFile} from 'node:fs/promises';
const first=await build({entryPoints:['app.js'],bundle:true,write:false,format:'iife',platform:'browser',target:'esnext'});
const transformed=await transformAsync(first.outputFiles[0].text,{
  configFile:false,babelrc:false,comments:false,
  presets:[['@babel/preset-env',{targets:{safari:'9',ie:'11'},useBuiltIns:'usage',corejs:'3.49',modules:'commonjs'}]]
});
const final=await build({stdin:{contents:transformed.code,resolveDir:process.cwd(),sourcefile:'legacy-build.js'},bundle:true,write:false,format:'iife',platform:'browser',target:'es5',minify:true,legalComments:'inline'});
await writeFile('app.legacy.js','/* Generated by npm run build:legacy. Do not edit directly. */\n'+final.outputFiles[0].text);
console.log('Built Safari 9 / ES5 bundle: '+final.outputFiles[0].text.length+' bytes');
